"""Writes the data-heavy TikZ figures of the thesis from the running example, so that the
figures in thesis/ and thesis-de/ always show what the notebooks compute."""
from pathlib import Path

import pandas as pd

# the figure folders of the English and the German thesis
FIGURE_DIRS = [Path("../../thesis/figures/tikz"), Path("../../thesis-de/figures/tikz")]

MONTHS = ["Jan", "Feb", "Mar", "Apr", "May", "Jun", "Jul", "Aug", "Sep", "Oct", "Nov", "Dec"]


def _days(times: pd.Series | pd.Timestamp, year: int) -> pd.Series | float:
    # days since the start of the year, the x-axis of the figure
    start = pd.Timestamp(f"{year}-01-01", tz="UTC")

    return (times - start) / pd.Timedelta("1D")


def _points(x, y, states, state) -> str:
    return ", ".join(f"{a:.2f}/{b:.2f}" for a, b, s in zip(x, y, states) if s == state)


def write_state_timeline(name: str, times: pd.Series, values: pd.Series, states: pd.Series,
                         y_range: tuple, y_ticks: list, y_label: str, drift: pd.Timestamp,
                         centers: list = None, year: int = 2020) -> list:
    """One symbol per feature window over the year: state 1 as blue circles, state 2 as orange
    squares and noise (state 0) as gray crosses. The figure defines no colors, the chapter
    defines stateA and stateB. Returns the written paths."""
    y_min, y_max = y_range
    height = y_max - y_min
    x, y = _days(times, year), values

    lines = [
        "% generated by notebooks/thesis, do not edit by hand",
        r"\begin{tikzpicture}[font=\small, x=0.0352cm, y=%.3fcm]" % (2.4 / height),
        r"	\draw[black!30] (0, %.2f) rectangle (366, %.2f);" % (y_min, y_max),
    ]

    # month names centered in their month, ticks between the months
    for k, month in enumerate(MONTHS):
        start = _days(pd.Timestamp(f"{year}-{k + 1:02d}-01", tz="UTC"), year)
        end = _days(pd.Timestamp(f"{year + (k == 11)}-{(k + 1) % 12 + 1:02d}-01", tz="UTC"), year)
        lines.append(r"	\node[below, inner sep=1pt] at (%.1f, %.2f) {%s};" % ((start + end) / 2, y_min - 0.03 * height, month))

        if k:
            lines.append(r"	\draw[black!30] (%.1f, %.2f) -- (%.1f, %.2f);" % (start, y_min, start, y_min + 0.04 * height))

    for tick in y_ticks:
        lines.append(r"	\draw (0, %.2f) -- ++(-0.08cm, 0) node[left] {$%g$};" % (tick, tick))

    lines.append(r"	\node[rotate=90] at (-34, %.2f) {%s};" % ((y_min + y_max) / 2, y_label))

    for center in centers or []:
        lines.append(r"	\draw[dotted, thick, black!60] (0, %.2f) -- (366, %.2f);" % (center, center))

    lines.append(r"	\draw[dashed, thick] (%.2f, %.2f) -- (%.2f, %.2f);" % (_days(drift, year), y_min, _days(drift, year), y_max))
    lines.append(r"	\foreach \x/\y in {%s} \fill[stateA] (\x, \y) circle (1.1pt);" % _points(x, y, states, 1))
    lines.append(r"	\foreach \x/\y in {%s} \fill[stateB] (\x, \y) ++(-1.1pt, -1.1pt) rectangle ++(2.2pt, 2.2pt);" % _points(x, y, states, 2))

    if (states == 0).any():
        lines.append(r"	\foreach \x/\y in {%s} \draw[black!60, line width=0.6pt] (\x, \y) ++(-1.5pt, -1.5pt) -- ++(3pt, 3pt) ++(0, -3pt) -- ++(-3pt, 3pt);" % _points(x, y, states, 0))

    lines.append(r"\end{tikzpicture}")

    return _write(name, lines)


def _write(name: str, lines: list) -> list:
    paths = []
    for folder in FIGURE_DIRS:
        folder.mkdir(parents=True, exist_ok=True)
        path = folder / f"{name}.tex"
        path.write_text("\n".join(lines) + "\n")
        paths.append(str(path))

    return paths


def write_log_trajectory(name: str, visits: pd.DataFrame, states: dict, drift: pd.Timestamp,
                         month_labels: bool = True, year: int = 2020) -> list:
    """The trajectory of the event log as one strip over the year, one box per visit. visits is
    what get_*_log_trajectory returns, states maps its state names to the styles stateA, stateB
    or noise of the chapter. A visit of a single feature window stays visible as a thin line."""
    lines = [
        "% generated by notebooks/thesis, do not edit by hand",
        r"\begin{tikzpicture}[font=\small, x=0.0352cm, y=1cm]",
    ]

    for _, visit in visits.iterrows():
        start, end = _days(visit["start"], year), _days(visit["end"], year)
        lines.append(r"	\fill[%s] (%.2f, 0) rectangle (%.2f, 0.5);" % (states[visit["state"]], start, max(end, start + 0.6)))

    lines.append(r"	\draw[black!30] (0, 0) rectangle (366, 0.5);")
    lines.append(r"	\draw[dashed, thick] (%.2f, -0.1) -- (%.2f, 0.6);" % (_days(drift, year), _days(drift, year)))

    for k, month in enumerate(MONTHS):
        start = _days(pd.Timestamp(f"{year}-{k + 1:02d}-01", tz="UTC"), year)
        end = _days(pd.Timestamp(f"{year + (k == 11)}-{(k + 1) % 12 + 1:02d}-01", tz="UTC"), year)

        if month_labels:
            lines.append(r"	\node[below, inner sep=1pt] at (%.1f, -0.05) {%s};" % ((start + end) / 2, month))

        if k:
            lines.append(r"	\draw[black!30] (%.1f, 0) -- (%.1f, -0.08);" % (start, start))

    lines.append(r"\end{tikzpicture}")

    return _write(name, lines)


def write_k_distance(name: str, distances, eps: float, min_samples: int, y_max: float = 3.0) -> list:
    """The sorted k-distance graph of DBSCAN with k = minPts, in ascending order as in
    plot_dbscan_k_distance, cut at y_max, and a dashed line at the chosen radius eps."""
    distances = sorted(distances)
    n = len(distances)
    width, height = 3.4, 2.4
    points = " ".join(f"({i * width / n:.3f}, {min(d, y_max) * height / y_max:.3f})" for i, d in enumerate(distances))

    lines = [
        "% generated by notebooks/thesis, do not edit by hand",
        r"\begin{tikzpicture}[font=\small]",
        r"	\draw[->] (0, 0) -- (%.2f, 0);" % (width + 0.3),
        r"	\draw[->] (0, 0) -- (0, %.2f);" % (height + 0.3),
        r"	\draw[thick] plot coordinates {%s};" % points,
        r"	\draw[dashed, thick] (0, %.3f) node[above right, inner sep=3pt] {$\varepsilon = %g$} -- (%.2f, %.3f);" % (eps * height / y_max, eps, width, eps * height / y_max),
    ]

    for tick in range(0, int(y_max) + 1):
        lines.append(r"	\draw (0, %.3f) -- (-0.08, %.3f) node[left] {%d};" % (tick * height / y_max, tick * height / y_max, tick))

    for tick in range(0, n + 1, 200):
        lines.append(r"	\draw (%.3f, 0) -- (%.3f, -0.08) node[below] {%d};" % (tick * width / n, tick * width / n, tick))

    lines.append(r"	\node[below=0.45cm] at (%.2f, 0) {Feature windows, sorted};" % (width / 2))
    lines.append(r"	\node[rotate=90] at (-0.6, %.2f) {%d-distance};" % (height / 2, min_samples))
    lines.append(r"\end{tikzpicture}")

    return _write(name, lines)


def _text_color(hex_color: str) -> str:
    # white text on dark fills, black on light ones, by the relative luminance of the fill
    channels = [int(hex_color[k:k + 2], 16) / 255 for k in (1, 3, 5)]
    linear = [c / 12.92 if c <= 0.04045 else ((c + 0.055) / 1.055) ** 2.4 for c in channels]
    luminance = 0.2126 * linear[0] + 0.7152 * linear[1] + 0.0722 * linear[2]

    return "white" if luminance < 0.18 else "black"


def write_case_trajectories(name: str, trajectories: dict, step: int = 20) -> list:
    """The trajectories of a few cases, one row each, over the minutes since the first event of
    the case. trajectories maps a row label to a frame with the columns state, minutes_from,
    minutes_to and color (a hex color of the state). A visit without duration, the last one,
    shows as a dot with its state next to it."""
    scale = 0.07
    longest = max(t["minutes_to"].max() for t in trajectories.values())
    end = step * (int(longest // step) + 1)

    lines = [
        "% generated by notebooks/thesis, do not edit by hand",
        r"\begin{tikzpicture}[font=\small, x=%gcm, y=1cm]" % scale,
    ]

    colors = {}
    for trajectory in trajectories.values():
        for color in trajectory["color"]:
            colors.setdefault(color, f"trajectory{len(colors)}")

    for color, name_ in colors.items():
        lines.append(r"	\definecolor{%s}{HTML}{%s}" % (name_, color[1:].upper()))

    for row, (label, trajectory) in enumerate(trajectories.items()):
        y = -0.9 * row
        lines.append(r"	\node[left] at (0, %.2f) {%s};" % (y + 0.275, label))

        for _, visit in trajectory.iterrows():
            fill, text = colors[visit["color"]], _text_color(visit["color"])

            if visit["minutes_to"] > visit["minutes_from"]:
                lines.append(r"	\fill[%s] (%.2f, %.2f) rectangle (%.2f, %.2f);" % (fill, visit["minutes_from"], y, visit["minutes_to"], y + 0.55))
                lines.append(r"	\node[text=%s] at (%.2f, %.2f) {$%s$};" % (text, (visit["minutes_from"] + visit["minutes_to"]) / 2, y + 0.275, visit["state"]))
            else:
                lines.append(r"	\fill[%s] (%.2f, %.2f) circle (3pt) node[right=2pt, text=black] {$%s$};" % (fill, visit["minutes_from"], y + 0.275, visit["state"]))

    bottom = -0.9 * (len(trajectories) - 1) - 0.15
    lines.append(r"	\draw[->] (0, %.2f) -- (%.2f, %.2f);" % (bottom, end + 6, bottom))

    for tick in range(0, end + 1, step):
        lines.append(r"	\draw (%d, %.2f) -- (%d, %.2f) node[below] {%d};" % (tick, bottom, tick, bottom - 0.08, tick))

    lines.append(r"	\node[below=0.45cm] at (%.1f, %.2f) {Minutes since the first event of the case};" % (end / 2, bottom))
    lines.append(r"\end{tikzpicture}")

    return _write(name, lines)


def write_u_matrix(name: str, u_matrix, low: float, high: float) -> list:
    """The u-matrix of a SOM as a gray grid with the values in the cells, from white at low to
    dark gray at high. The rows and columns are numbered from 1 as in the thesis."""
    size = 1.1
    rows, columns = len(u_matrix), len(u_matrix[0])

    lines = [
        "% generated by notebooks/thesis, do not edit by hand",
        r"\begin{tikzpicture}[font=\small]",
    ]

    for r in range(rows):
        lines.append(r"	\node at (-0.3, %.3f) {%d};" % (-(r + 0.5) * size, r + 1))

        for c in range(columns):
            value = u_matrix[r][c]
            shade = round(70 * min(max((value - low) / (high - low), 0), 1))
            text = "white" if shade > 45 else "black"
            lines.append(r"	\fill[black!%d] (%.3f, %.3f) rectangle ++(%.2f, %.2f);" % (shade, c * size, -r * size, size, -size))
            lines.append(r"	\node[text=%s] at (%.3f, %.3f) {%.2f};" % (text, (c + 0.5) * size, -(r + 0.5) * size, value))

    for c in range(columns):
        lines.append(r"	\node at (%.3f, 0.3) {%d};" % ((c + 0.5) * size, c + 1))

    lines.append(r"	\draw[black!50] (0, 0) grid[step=%.2f] (%.3f, %.3f);" % (size, columns * size, -rows * size))
    lines.append(r"\end{tikzpicture}")

    return _write(name, lines)


def write_drift_signal(name: str, drift_signal: pd.DataFrame, signal_window: str, drift: pd.Timestamp,
                       y_max: float, y_ticks: list, y_label: str = "Drift score (KL)", year: int = 2020) -> list:
    """The drift signal over the year as steps: every signal window is a horizontal line at its
    drift score from its start to its end, cut at the bounds of the year, with the area below
    in gray. drift_signal is what compute_drift_signal returns, signal windows without a drift
    score leave a gap."""
    length = pd.Timedelta(signal_window)

    # runs of adjacent signal windows with a drift score, each run one path
    runs, run, end = [], [], None
    for _, window in drift_signal.iterrows():
        start = max(_days(window["signal_window"], year), 0)

        if pd.isna(window["drift_score"]) or (run and start != end):
            if run:
                runs.append(run)
            run = []

        if pd.notna(window["drift_score"]):
            end = min(_days(window["signal_window"] + length, year), 366)
            score = min(window["drift_score"], y_max)
            run += [(start, score), (end, score)]

    if run:
        runs.append(run)

    lines = [
        "% generated by notebooks/thesis, do not edit by hand",
        r"\begin{tikzpicture}[font=\small, x=0.0352cm, y=%.4fcm]" % (2.4 / y_max),
    ]

    for run in runs:
        points = " -- ".join(f"({x:.2f}, {y:.4f})" for x, y in run)
        lines.append(r"	\fill[black!15] (%.2f, 0) -- %s -- (%.2f, 0) -- cycle;" % (run[0][0], points, run[-1][0]))
        lines.append(r"	\draw[thick] %s;" % points)

    lines.append(r"	\draw[black!30] (0, 0) rectangle (366, %g);" % y_max)

    # month names centered in their month, ticks between the months
    for k, month in enumerate(MONTHS):
        start = _days(pd.Timestamp(f"{year}-{k + 1:02d}-01", tz="UTC"), year)
        end = _days(pd.Timestamp(f"{year + (k == 11)}-{(k + 1) % 12 + 1:02d}-01", tz="UTC"), year)
        lines.append(r"	\node[below, inner sep=1pt] at (%.1f, %.4f) {%s};" % ((start + end) / 2, -0.03 * y_max, month))

        if k:
            lines.append(r"	\draw[black!30] (%.1f, 0) -- (%.1f, %.4f);" % (start, start, 0.04 * y_max))

    for tick in y_ticks:
        lines.append(r"	\draw (0, %g) -- ++(-0.08cm, 0) node[left] {$%g$};" % (tick, tick))

    lines.append(r"	\node[rotate=90] at (-34, %g) {%s};" % (y_max / 2, y_label))
    lines.append(r"	\draw[dashed, thick] (%.2f, 0) -- (%.2f, %g);" % (_days(drift, year), _days(drift, year), y_max))
    lines.append(r"\end{tikzpicture}")

    return _write(name, lines)


def write_abstraction(name: str, text: str, width: int = 84) -> list:
    """An abstraction as the llm reads it, in a verbatim block, every line wrapped to width
    characters so that it fits the page. Wrapped list items keep the indent of their dash."""
    import textwrap

    lines = ["% generated by notebooks/thesis, do not edit by hand", r"\begin{verbatim}"]

    for line in text.split("\n"):
        indent = "  " if line.startswith("- ") else ""
        lines += textwrap.wrap(line, width=width, subsequent_indent=indent) or [""]

    lines.append(r"\end{verbatim}")

    return _write(name, lines)
